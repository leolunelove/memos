export function preference(key,fallback){try{return localStorage.getItem('memos-'+key)||fallback;}catch{return fallback;}}
export function savePreference(key,value){try{localStorage.setItem('memos-'+key,value);}catch{}}
const saved=preference('language','');
export let language=saved==='en'||saved==='zh-CN'?saved:/^zh(?:-|$)/i.test(navigator.language||'')?'zh-CN':'en';
export function t(key,values={}){return (language==='zh-CN'?zh[key]||key:key).replace(/\{(\w+)\}/g,(_,k)=>String(values[k]??'{'+k+'}'));}
const staticText=[],staticAttrs=[];
export function initTranslations(){
  const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){
    const node=walker.currentNode,key=node.textContent.trim();
    if(zh[key])staticText.push({node,key,prefix:node.textContent.match(/^\s*/)[0],suffix:node.textContent.match(/\s*$/)[0]});
  }
  for(const node of document.querySelectorAll('[aria-label],[title],[placeholder],meta[name="description"]'))for(const attr of ['aria-label','title','placeholder','content']){
    const key=node.getAttribute(attr);if(zh[key])staticAttrs.push({node,attr,key});
  }
  applyTranslations();
}
export function applyTranslations(){
  document.documentElement.lang=language;
  for(const {node,key,prefix,suffix} of staticText)if(node.isConnected)node.textContent=prefix+t(key)+suffix;
  for(const {node,attr,key} of staticAttrs)node.setAttribute(attr,t(key));
  document.getElementById('language').value=language;
}
export function setLanguage(value){language=value==='zh-CN'?'zh-CN':'en';savePreference('language',language);applyTranslations();}
